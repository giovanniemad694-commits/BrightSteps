/*
# Coptic Patriarchs Archive — Schema & Seed Data

## Overview
Creates the database for an educational documentary archive of Coptic Orthodox
Patriarchs who preserved and defended the Christian faith.

## Tables
1. `patriarchs` — main table storing patriarch biographies and metadata
2. `patriarch_events` — important historical events for each patriarch
3. `patriarch_sources` — references and sources for each patriarch

## Security (RLS)
- All tables are publicly readable (anon + authenticated SELECT) since this
  is a public educational archive.
- INSERT / UPDATE / DELETE restricted to authenticated users (admin area).
- This allows the public to browse, while only logged-in admins can edit.
*/

-- ============================================================
-- 1. PATRIARCHS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS patriarchs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name_ar text NOT NULL,
  name_en text NOT NULL,
  papal_number integer NOT NULL,
  birth_date text,
  death_date text,
  papacy_start text,
  papacy_end text,
  century integer NOT NULL,
  short_bio_ar text NOT NULL,
  biography_ar text NOT NULL,
  historical_background_ar text,
  faith_defense_ar text,
  challenges_ar text,
  contributions_ar text,
  image_url text,
  image_source text,
  image_credit text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Unique index on papal_number since each number is used once
CREATE UNIQUE INDEX IF NOT EXISTS idx_patriarchs_papal_number ON patriarchs(papal_number);
CREATE INDEX IF NOT EXISTS idx_patriarchs_century ON patriarchs(century);

ALTER TABLE patriarchs ENABLE ROW LEVEL SECURITY;

-- Public read
DROP POLICY IF EXISTS "public_select_patriarchs" ON patriarchs;
CREATE POLICY "public_select_patriarchs"
ON patriarchs FOR SELECT
TO anon, authenticated USING (true);

-- Admin write (authenticated only)
DROP POLICY IF EXISTS "admin_insert_patriarchs" ON patriarchs;
CREATE POLICY "admin_insert_patriarchs"
ON patriarchs FOR INSERT
TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "admin_update_patriarchs" ON patriarchs;
CREATE POLICY "admin_update_patriarchs"
ON patriarchs FOR UPDATE
TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "admin_delete_patriarchs" ON patriarchs;
CREATE POLICY "admin_delete_patriarchs"
ON patriarchs FOR DELETE
TO authenticated USING (true);

-- ============================================================
-- 2. PATRIARCH_EVENTS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS patriarch_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  patriarch_id uuid NOT NULL REFERENCES patriarchs(id) ON DELETE CASCADE,
  title_ar text NOT NULL,
  description_ar text,
  event_date text,
  event_year integer,
  sort_order integer DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_events_patriarch_id ON patriarch_events(patriarch_id);

ALTER TABLE patriarch_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_select_events" ON patriarch_events;
